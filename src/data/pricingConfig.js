function buildTiers(coefficients, grandSpacesFrom = 351) {
  return TIER_TEMPLATE.map((tier) => ({
    category: tier.min >= grandSpacesFrom ? "Grands espaces" : "Standard",
    min: tier.min,
    max: tier.max,
    coeff: coefficients[tier.band],
    base: tier.base,
  }));
}

